<script setup lang="ts">
import { computed, nextTick, onMounted, ref, useId, useTemplateRef, watch } from "vue";
import {
  ALL_COUNTRIES,
  COUNTRIES_BY_DIAL_CODE_LENGTH,
  DEFAULT_COUNTRY,
  getLocalizedCountries,
  type CountryCallingCode,
} from "@/data/countries";
import type { PhoneInputLabels } from "@/lib/form-copy";

interface Props {
  ariaDescribedby?: string | undefined;
  ariaInvalid?: "true" | "false" | boolean;
  id?: string;
  initialValue?: string;
  labels?: PhoneInputLabels;
  locale?: string;
  name?: string;
  placeholder?: string;
  required?: boolean;
  toolparamdescription?: string;
}

const props = withDefaults(defineProps<Props>(), {
  id: "phone",
  locale: "en",
  name: "phone",
  required: true,
  placeholder: "(555) 000-0000",
  ariaInvalid: "false",
  initialValue: "",
  toolparamdescription: "International phone or WhatsApp number including country code",
});

// CSS --anchor-name breaks on colons generated by Vue useId().
const dropdownId = `phone-dropdown-${useId().replaceAll(":", "")}`;
const dropdownRef = useTemplateRef<HTMLElement>("dropdownRef");
const searchInputRef = useTemplateRef<HTMLInputElement>("searchInputRef");
const listRef = useTemplateRef<HTMLElement>("listRef");

const isOpen = ref(false);
const searchQuery = ref("");
const selectedCountry = ref<CountryCallingCode>(DEFAULT_COUNTRY);
const nationalNumber = ref("");
const isMounted = ref(false);

onMounted(() => {
  isMounted.value = true;
});

const localizedCountries = computed(() =>
  isMounted.value ? getLocalizedCountries(props.locale) : ALL_COUNTRIES,
);
const activeCountry = computed(
  () =>
    localizedCountries.value.find((c) => c.code === selectedCountry.value.code)
    ?? selectedCountry.value,
);

const triggerAriaPrefix = computed(
  () => props.labels?.triggerAriaPrefix ?? "Selected country dial code",
);
const listboxAriaPrefix = computed(
  () => props.labels?.listboxAriaPrefix ?? "Select country phone code",
);
const searchPlaceholder = computed(
  () => props.labels?.searchPlaceholder ?? "Search country or code...",
);
const emptySearchLabel = computed(() => props.labels?.emptySearch ?? "No countries found");

function cleanNumber(val: string): string {
  return val.replaceAll(/[^\d\s().+-]/g, "").trim();
}

const fullPhoneNumber = computed(() => {
  const clean = cleanNumber(nationalNumber.value);
  if (!clean) return "";
  if (clean.startsWith("+")) return clean;
  const normalized = clean.startsWith("0") ? clean.slice(1).trim() : clean;
  return `${selectedCountry.value.dialCode} ${normalized}`.trim();
});

const filteredCountries = computed(() => {
  const query = searchQuery.value.trim().toLowerCase();
  const countries = localizedCountries.value;
  return query ? countries.filter((c) => c.searchText.includes(query)) : countries;
});

function parsePhonePrefix(raw: string): void {
  if (raw.startsWith("+")) {
    const matched = COUNTRIES_BY_DIAL_CODE_LENGTH.find((c) => raw.startsWith(c.dialCode));
    if (matched) {
      selectedCountry.value = matched;
      nationalNumber.value = raw.slice(matched.dialCode.length).trim();
      return;
    }
  }
  nationalNumber.value = raw;
}

function handleToggle(event: ToggleEvent): void {
  const open = event.newState === "open";
  isOpen.value = open;
  if (!open) return;

  searchQuery.value = "";
  void nextTick(() => {
    searchInputRef.value?.focus();
  });
}

function selectCountry(country: CountryCallingCode): void {
  selectedCountry.value = country;
  searchQuery.value = "";
  dropdownRef.value?.hidePopover();
}

function handleInput(event: Event): void {
  if (!(event.target instanceof HTMLInputElement)) return;
  parsePhonePrefix(event.target.value);
}

function handleListKeydown(event: KeyboardEvent): void {
  const options = [
    ...(listRef.value?.querySelectorAll<HTMLButtonElement>('[role="option"]') ?? []),
  ];
  if (options.length === 0) return;

  const currentIndex = options.indexOf(document.activeElement as HTMLButtonElement);
  if (event.key === "ArrowDown") {
    event.preventDefault();
    const next = options[(currentIndex + 1) % options.length];
    next?.focus();
  } else if (event.key === "ArrowUp") {
    event.preventDefault();
    if (currentIndex <= 0) {
      searchInputRef.value?.focus();
      return;
    }
    options[currentIndex - 1]?.focus();
  }
}

function handleSearchKeydown(event: KeyboardEvent): void {
  event.stopPropagation();
  if (event.key === "ArrowDown") {
    event.preventDefault();
    listRef.value?.querySelector<HTMLButtonElement>('[role="option"]')?.focus();
  } else if (event.key === "Enter") {
    const first = filteredCountries.value[0];
    if (first) {
      event.preventDefault();
      selectCountry(first);
    }
  }
}

watch(
  () => props.initialValue,
  (val) => {
    if (!val) return;
    parsePhonePrefix(val);
  },
  { immediate: true },
);
</script>

<template>
  <div class="relative w-full [anchor-scope:--phone-anchor]">
    <div
      class="group flex h-12 w-full items-center rounded-xl border border-stone-200/90 bg-stone-50/50 transition-colors [anchor-name:--phone-anchor] focus-within:border-orange-500 focus-within:bg-white focus-within:ring-2 focus-within:ring-orange-500/20 has-[input:user-invalid]:border-red-400/80 dark:border-white/10 dark:bg-white/5 dark:focus-within:border-orange-500 dark:focus-within:bg-white/10"
      :class="{ 'border-red-400 bg-red-50/20': ariaInvalid === 'true' || ariaInvalid === true }"
    >
      <button
        type="button"
        :popovertarget="dropdownId"
        popovertargetaction="toggle"
        class="flex h-full shrink-0 cursor-pointer items-center gap-1.5 rounded-s-xl border-e border-stone-200/80 px-3.5 transition-colors hover:bg-stone-100/70 focus:bg-stone-100 focus:outline-hidden dark:border-white/10 dark:hover:bg-white/10 dark:focus:bg-white/10"
        :aria-expanded="isOpen"
        :aria-controls="dropdownId"
        aria-haspopup="listbox"
        :aria-label="`${activeCountry.dialCode} - ${triggerAriaPrefix}: ${activeCountry.name}`"
      >
        <span class="font-sans text-xs font-semibold text-stone-800 dark:text-mist-100">
          {{ selectedCountry.dialCode }}
        </span>
        <svg
          class="size-3.5 text-stone-400 transition-colors dark:text-mist-400"
          :class="{ 'text-stone-700 dark:text-mist-200': isOpen }"
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          stroke-width="1.75"
          aria-hidden="true"
        >
          <path
            d="M13.5 19.5L12 21L6 15"
            stroke-linecap="round"
            stroke-linejoin="round"
          />
          <path
            d="M16.5 16.5L18 15"
            stroke-linecap="round"
            stroke-linejoin="round"
          />
          <path
            d="M13.5 4.5L12 3L6 9"
            stroke-linecap="round"
            stroke-linejoin="round"
          />
          <path
            d="M16.5 7.5L18 9"
            stroke-linecap="round"
            stroke-linejoin="round"
          />
        </svg>
      </button>

      <div class="relative flex h-full flex-1 items-center">
        <input
          :id="id"
          name="phoneNational"
          type="tel"
          :value="nationalNumber"
          :placeholder="placeholder"
          minlength="6"
          maxlength="20"
          autocomplete="tel-national"
          :required="required"
          :aria-invalid="ariaInvalid"
          :aria-describedby="ariaDescribedby"
          class="peer size-full bg-transparent ps-10.5 pe-4 font-sans text-sm text-stone-900 placeholder:text-stone-400 focus:outline-hidden dark:text-mist-100 dark:placeholder:text-mist-500"
          @input="handleInput"
        />
        <svg
          class="pointer-events-none absolute inset-s-3.5 top-1/2 size-4.5 -translate-y-1/2 text-stone-400 transition-colors peer-focus:text-orange-500 dark:text-stone-500"
          viewBox="0 0 24 24"
          fill="none"
          aria-hidden="true"
        >
          <path
            d="M4.00655 7.93309C3.93421 9.84122 4.41713 13.0817 7.6677 16.3323C8.45191 17.1165 9.23553 17.7396 10 18.2327M5.53781 4.93723C6.93076 3.54428 9.15317 3.73144 10.0376 5.31617L10.6866 6.4791C11.2723 7.52858 11.0372 8.90532 10.1147 9.8278C10.1147 9.8278 10.1147 9.8278 10.1147 9.8278C10.1146 9.82792 8.99588 10.9468 11.0245 12.9755C13.0525 15.0035 14.1714 13.8861 14.1722 13.8853C14.1722 13.8853 14.1722 13.8853 14.1722 13.8853C15.0947 12.9628 16.4714 12.7277 17.5209 13.3134L18.6838 13.9624C20.2686 14.8468 20.4557 17.0692 19.0628 18.4622C18.2258 19.2992 17.2004 19.9505 16.0669 19.9934C15.2529 20.0243 14.1963 19.9541 13 19.6111"
            stroke="currentColor"
            stroke-width="1.5"
            stroke-linecap="round"
          />
        </svg>
      </div>

      <input
        type="hidden"
        name="phoneCountryCode"
        :value="selectedCountry.dialCode"
      />
      <input
        type="hidden"
        :name="name"
        :value="fullPhoneNumber"
        :toolparamdescription="toolparamdescription"
      />
    </div>

    <div
      :id="dropdownId"
      ref="dropdownRef"
      popover="auto"
      class="fixed inset-0 z-50 m-auto w-[min(24rem,calc(100vw-2rem))] overflow-hidden rounded-xl border border-stone-200/90 bg-white p-0 text-stone-900 opacity-0 shadow-xl shadow-stone-900/10 transition-[opacity,transform,display,overlay] transition-discrete duration-200 [position-anchor:--phone-anchor] backdrop:bg-black/20 open:opacity-100 supports-[top:anchor(bottom)]:inset-auto supports-[top:anchor(bottom)]:top-[calc(anchor(bottom)+6px)] supports-[top:anchor(bottom)]:left-[anchor(left)] supports-[top:anchor(bottom)]:m-0 supports-[top:anchor(bottom)]:[position-try-fallbacks:flip-block] supports-[top:anchor(bottom)]:backdrop:bg-transparent supports-[width:anchor-size(width)]:w-[anchor-size(width)] dark:border-white/10 dark:bg-surface-card dark:text-mist-100 dark:shadow-[0_16px_40px_rgba(0,0,0,0.65)] starting:open:opacity-0"
      @toggle="handleToggle"
    >
      <div
        class="relative border-b border-stone-100 bg-stone-50/70 p-2 dark:border-white/10 dark:bg-white/5"
      >
        <svg
          xmlns="http://www.w3.org/2000/svg"
          class="pointer-events-none absolute inset-s-4.5 top-1/2 size-3.5 -translate-y-1/2 text-stone-400 dark:text-mist-400"
          viewBox="0 0 24 24"
          fill="none"
          stroke-width="1.5"
          aria-hidden="true"
        >
          <path
            d="M20 20L22 22"
            stroke-linecap="round"
            stroke="currentColor"
          />
          <path
            d="M6.75 3.27093C8.14732 2.46262 9.76964 2 11.5 2C16.7467 2 21 6.25329 21 11.5C21 16.7467 16.7467 21 11.5 21C6.25329 21 2 16.7467 2 11.5C2 9.76964 2.46262 8.14732 3.27093 6.75"
            stroke-linecap="round"
            stroke="currentColor"
          />
        </svg>
        <input
          :id="`${dropdownId}-search`"
          ref="searchInputRef"
          v-model="searchQuery"
          type="text"
          autocomplete="off"
          :aria-label="searchPlaceholder"
          :placeholder="searchPlaceholder"
          class="h-8.5 w-full rounded-lg border border-stone-200/80 bg-white ps-8 pe-3 font-sans text-xs text-stone-900 placeholder:text-stone-400 focus:border-orange-500 focus:ring-2 focus:ring-orange-500/30 focus:outline-hidden dark:border-white/10 dark:bg-surface-base dark:text-mist-100 dark:placeholder:text-mist-500 dark:focus:border-orange-500"
          @keydown="handleSearchKeydown"
        />
      </div>

      <div
        class="flex flex-col px-(--scrollbar-space) py-1 [--scrollbar-space:8px] [--scrollbar-theme:hsl(0deg_0%_75%)]"
      >
        <div
          ref="listRef"
          role="listbox"
          :aria-label="`${listboxAriaPrefix}: ${activeCountry.name}`"
          class="max-h-60 divide-y divide-stone-100/60 overflow-x-hidden overflow-y-auto overscroll-y-contain pe-(--scrollbar-space) supports-[-moz-appearance:none]:scrollbar-thin supports-[-moz-appearance:none]:[scrollbar-color:color-mix(in_sRGB,var(--scrollbar-theme,hsl(0deg_0%_75%)),transparent_28%)_transparent] dark:divide-white/5 [&::-webkit-scrollbar]:w-2 [&::-webkit-scrollbar-button]:hidden [&::-webkit-scrollbar-button]:size-0 [&::-webkit-scrollbar-thumb]:rounded-[1000px] [&::-webkit-scrollbar-thumb]:bg-[color-mix(in_sRGB,var(--scrollbar-theme,hsl(0deg_0%_75%)),transparent_28%)] [&::-webkit-scrollbar-thumb:hover]:bg-[color-mix(in_sRGB,var(--scrollbar-theme,hsl(0deg_0%_75%)),transparent_12%)] [&::-webkit-scrollbar-track]:my-2.5 [&::-webkit-scrollbar-track]:rounded-[1000px] [&::-webkit-scrollbar-track]:bg-[color-mix(in_sRGB,var(--scrollbar-theme,hsl(0deg_0%_75%)),transparent_82%)] [&::-webkit-scrollbar-track]:bg-clip-padding"
          tabindex="-1"
          @keydown="handleListKeydown"
        >
          <button
            v-for="country in filteredCountries"
            :key="country.code"
            type="button"
            role="option"
            :aria-selected="country.code === selectedCountry.code"
            class="flex min-h-9 w-full cursor-pointer items-center justify-between gap-2 rounded-none px-3 py-2 text-start transition-colors hover:bg-stone-100 focus:bg-stone-100 focus:outline-hidden focus-visible:ring-2 focus-visible:ring-orange-500 focus-visible:ring-inset active:bg-stone-200/70 dark:hover:bg-white/5 dark:focus:bg-white/5"
            :class="{
              'bg-stone-100 font-medium text-stone-900 dark:bg-white/10 dark:text-mist-100':
                country.code === selectedCountry.code,
            }"
            @click="selectCountry(country)"
          >
            <span
              class="min-w-0 flex-1 truncate font-sans text-xs text-stone-800 dark:text-mist-200"
            >
              {{ country.name }}
            </span>
            <bdi
              dir="ltr"
              class="shrink-0 font-sans text-xs font-medium text-stone-600 dark:text-mist-300"
            >
              {{ country.dialCode }}
            </bdi>
          </button>

          <div
            v-if="filteredCountries.length === 0"
            class="px-3 py-6 text-center font-sans text-xs text-stone-600 dark:text-mist-300"
          >
            {{ emptySearchLabel }}
          </div>
        </div>
      </div>
    </div>
  </div>
</template>
